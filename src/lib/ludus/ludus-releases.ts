import { parseLudusSemver } from "@/lib/ludus/ludus-version"

/** GitLab project badsectorlabs/ludus. The package URL is built from this id. */
export const LUDUS_GITLAB_PROJECT_ID = "54052321"
export const LUDUS_RELEASES_PAGE = "https://gitlab.com/badsectorlabs/ludus/-/releases"

export type LudusVersionRelation = "upgrade" | "current" | "older"

export type LudusRelease = {
  tag: string
  name: string
  publishedAt: string
  htmlUrl: string
  notesExcerpt: string
  notes: string
  prerelease: boolean
  relation: LudusVersionRelation
  canUpgrade: boolean
}

export type LudusReleasesSnapshot = {
  current: string
  latestStable: string | null
  updateAvailable: boolean
  releases: LudusRelease[]
  releasesUrl: string
  error?: string
}

export type LudusGitlabRelease = {
  tag_name?: string
  name?: string
  description?: string
  released_at?: string
  upcoming_release?: boolean
}

/** Host upgrade accepts this shape. The package path uses the same string. */
export function normalizeLudusTag(tag: string): string | null {
  const t = tag.trim().replace(/^v/, "")
  return /^[0-9]+\.[0-9]+\.[0-9]+(-rc[0-9]+)?$/.test(t) ? t : null
}

/** The X.Y.Z (or X.Y.Z-rcN) inside a Ludus version string. */
/** Version string from a Ludus `/version` body, including nested `{ result: { version } }`. */
export function ludusVersionText(data: unknown): string {
  if (typeof data === "string") return data.trim()
  if (!data || typeof data !== "object") return ""
  const record = data as Record<string, unknown>
  const result = record.result
  if (typeof result === "string" && result.trim()) return result.trim()
  if (result && typeof result === "object") {
    const inner = result as Record<string, unknown>
    if (typeof inner.version === "string" && inner.version.trim()) return inner.version.trim()
    if (typeof inner.result === "string" && inner.result.trim()) return inner.result.trim()
  }
  if (typeof record.version === "string") return record.version.trim()
  return ""
}

export function ludusVersionLabel(raw: string): string {
  const match = raw.match(/(\d+\.\d+\.\d+(?:-rc\d+)?)/)
  return match?.[1] ?? ""
}

export function isLudusPrerelease(tag: string): boolean {
  return /-(?:rc|beta|alpha|pre)\b/i.test(tag)
}

/** Stable ranks above a prerelease of the same triple. */
function prereleaseRank(tag: string): number {
  const m = tag.match(/-(rc|beta|alpha)\.?(\d+)?/i)
  if (!m) return 1_000_000
  const kind = m[1].toLowerCase()
  const n = Number(m[2] ?? 0)
  const base = kind === "alpha" ? 0 : kind === "beta" ? 1_000 : 2_000
  return base + n
}

/** Negative when left is older. Null when either side has no semver. */
export function compareLudusVersions(left: string, right: string): number | null {
  const a = parseLudusSemver(left)
  const b = parseLudusSemver(right)
  if (!a || !b) return null
  for (let i = 0; i < 3; i++) {
    if (a[i] !== b[i]) return a[i] - b[i]
  }
  return prereleaseRank(left) - prereleaseRank(right)
}

function excerpt(description: string | undefined): string {
  const text = (description ?? "").replace(/\s+/g, " ").trim()
  if (text.length <= 180) return text
  return `${text.slice(0, 177)}...`
}

/** Release text for one Ludus version, without the repeated changelog banner. */
export function ludusReleaseNotes(description: string | undefined): string {
  const text = (description ?? "")
    .replace(/\r\n/g, "\n")
    .replace(/^#\s+Changelog\s*\n+/i, "")
    .replace(/^All notable changes to this project will be documented in this file\.[ \t]*\n+/i, "")
    .replace(/\n*<!--\s*generated by git-cliff\s*-->\s*$/i, "")
    .replace(/^##\s+\[[^\]]+\].*\n+/m, "")
    .trim()
  if (text.length <= 12000) return text
  return `${text.slice(0, 11997)}...`
}

export function mapLudusUpgradeError(stderr: string): string {
  const line = stderr.trim().split("\n").filter(Boolean).pop() ?? ""
  if (line.includes("not installed")) return "Ludus is not installed on this host."
  if (line.includes("installing")) return "A Ludus install is already running."
  if (line.includes("busy")) return "Ansible or Packer is running. Wait until that finishes."
  if (line.includes("running")) return "A Ludus upgrade is already running."
  if (line.includes("operation not allowed")) {
    return "The host helper does not include Ludus upgrades yet. Install lux-host from Settings → Auth, then try again."
  }
  if (line.includes("systemd-run")) return "This host has no systemd-run, so the upgrade cannot continue in the background."
  if (line.includes("curl")) return "curl is not installed on the Ludus host."
  if (line.includes("version")) return "That version is not a release this host will install."
  const cleaned = line.replace(/^lux-host:\s*/, "").trim()
  return cleaned || "The host did not start the upgrade."
}

export function releasesFromGitlab(json: unknown): LudusGitlabRelease[] {
  if (!Array.isArray(json)) return []
  const out: LudusGitlabRelease[] = []
  for (const row of json) {
    if (!row || typeof row !== "object") continue
    const rec = row as Record<string, unknown>
    const tag = typeof rec.tag_name === "string"
      ? rec.tag_name
      : typeof rec.name === "string"
        ? rec.name
        : ""
    if (!tag.trim()) continue
    if (rec.upcoming_release === true) continue
    const commit = rec.commit && typeof rec.commit === "object"
      ? (rec.commit as Record<string, unknown>)
      : null
    const released = typeof rec.released_at === "string"
      ? rec.released_at
      : typeof commit?.created_at === "string"
        ? commit.created_at
        : ""
    out.push({
      tag_name: tag.trim(),
      name: typeof rec.name === "string" ? rec.name : tag.trim(),
      description: typeof rec.description === "string"
        ? rec.description
        : typeof rec.message === "string"
          ? rec.message
          : "",
      released_at: released,
    })
  }
  return out
}

export function buildLudusReleasesSnapshot(
  currentRaw: string,
  rows: LudusGitlabRelease[],
  error?: string,
): LudusReleasesSnapshot {
  const current = currentRaw.trim()
  const seen = new Set<string>()
  const releases: LudusRelease[] = []
  for (const row of rows) {
    const raw = (row.tag_name ?? "").trim()
    if (!raw || !parseLudusSemver(raw)) continue
    const tag = normalizeLudusTag(raw) ?? raw.replace(/^v/, "")
    if (seen.has(tag)) continue
    seen.add(tag)
    const prerelease = isLudusPrerelease(tag)
    const cmp = compareLudusVersions(tag, current)
    const relation: LudusVersionRelation =
      cmp == null ? "older" : cmp === 0 ? "current" : cmp > 0 ? "upgrade" : "older"
    releases.push({
      tag,
      name: (row.name ?? tag).trim() || tag,
      publishedAt: (row.released_at ?? "").trim(),
      htmlUrl: `${LUDUS_RELEASES_PAGE}/${encodeURIComponent(raw)}`,
      notesExcerpt: excerpt(row.description),
      notes: ludusReleaseNotes(row.description),
      prerelease,
      relation,
      canUpgrade: relation === "upgrade" && !prerelease && normalizeLudusTag(tag) != null,
    })
  }
  releases.sort((a, b) => (compareLudusVersions(b.tag, a.tag) ?? 0))
  const latestStable = releases.find((r) => !r.prerelease)?.tag ?? null
  const updateAvailable = latestStable != null && compareLudusVersions(latestStable, current) != null
    && (compareLudusVersions(latestStable, current) ?? 0) > 0
  return {
    current,
    latestStable,
    updateAvailable,
    releases,
    releasesUrl: LUDUS_RELEASES_PAGE,
    ...(error ? { error } : {}),
  }
}
