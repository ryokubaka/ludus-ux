import { describe, expect, it } from "vitest"
import {
  buildLudusReleasesSnapshot,
  compareLudusVersions,
  mapLudusUpgradeError,
  ludusVersionLabel,
  ludusVersionText,
  ludusReleaseNotes,
  normalizeLudusTag,
  releasesFromGitlab,
} from "@/lib/ludus/ludus-releases"

describe("ludus releases", () => {
  it("keeps one version's notes and drops the changelog banner", () => {
    const notes = ludusReleaseNotes(
      "# Changelog\n\nAll notable changes to this project will be documented in this file.\n\n## [2.3.10] - 2026-10-23\n\n### Bug Fixes\n\n- *(templates)* Fix Kali\n\n<!-- generated by git-cliff -->\n",
    )
    expect(notes).toBe("### Bug Fixes\n\n- *(templates)* Fix Kali")
  })

  it("reads a version from a string or a nested Ludus payload", () => {
    expect(ludusVersionText("2.3.8")).toBe("2.3.8")
    expect(ludusVersionText({ result: "Ludus Server 2.3.8" })).toBe("Ludus Server 2.3.8")
    expect(ludusVersionText({ result: { version: "2.3.8" } })).toBe("2.3.8")
    expect(ludusVersionText({ version: "2.3.8" })).toBe("2.3.8")
    expect(ludusVersionText(null)).toBe("")
  })

  it("reads the semver out of a Ludus version banner", () => {
    expect(ludusVersionLabel("Ludus Server 2.3.8+c6528ccc - community")).toBe("2.3.8")
  })

  it("accepts a version the host package URL can use", () => {
    expect(normalizeLudusTag("v2.3.10")).toBe("2.3.10")
    expect(normalizeLudusTag("2.3.10-rc1")).toBe("2.3.10-rc1")
    expect(normalizeLudusTag("2.3.10;id")).toBeNull()
    expect(normalizeLudusTag("2.3.10-beta.1")).toBeNull()
  })

  it("ranks a stable release above its release candidate", () => {
    expect(compareLudusVersions("2.3.10", "2.3.5")).toBeGreaterThan(0)
    expect(compareLudusVersions("2.3.5", "2.3.5-rc1")).toBeGreaterThan(0)
    expect(compareLudusVersions("Ludus server v2.3.5", "2.3.5")).toBe(0)
  })

  it("marks a newer stable release as an upgrade and skips a beta install", () => {
    const snap = buildLudusReleasesSnapshot("Ludus server v2.3.5", [
      { tag_name: "2.3.10", released_at: "2026-10-23T00:00:00Z", description: "Latest" },
      { tag_name: "2.3.5", released_at: "2026-06-01T00:00:00Z" },
      { tag_name: "2.3.4", released_at: "2026-05-01T00:00:00Z" },
      { tag_name: "2.4.0-beta.1", released_at: "2026-11-01T00:00:00Z" },
      { tag_name: "not-a-version" },
    ])
    expect(snap.latestStable).toBe("2.3.10")
    expect(snap.updateAvailable).toBe(true)
    expect(snap.releases.map((r) => r.tag)).toEqual(["2.4.0-beta.1", "2.3.10", "2.3.5", "2.3.4"])
    expect(snap.releases.find((r) => r.tag === "2.3.10")?.canUpgrade).toBe(true)
    expect(snap.releases.find((r) => r.tag === "2.3.5")?.relation).toBe("current")
    expect(snap.releases.find((r) => r.tag === "2.3.4")?.canUpgrade).toBe(false)
    expect(snap.releases.find((r) => r.tag === "2.4.0-beta.1")?.canUpgrade).toBe(false)
  })

  it("turns a host refusal into a short reason", () => {
    expect(mapLudusUpgradeError("lux-host: busy\n")).toMatch(/Ansible or Packer/)
    expect(mapLudusUpgradeError("lux-host: version")).toMatch(/not a release/)
  })

  it("reads a GitLab releases payload and a tags payload", () => {
    expect(releasesFromGitlab([
      { tag_name: "2.3.10", upcoming_release: true },
      { name: "2.3.9", commit: { created_at: "2026-01-01T00:00:00Z" }, message: "tag" },
    ]).map((r) => r.tag_name)).toEqual(["2.3.9"])
  })
})
